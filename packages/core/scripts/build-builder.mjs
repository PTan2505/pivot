// Bundles the cloud builder (src/builder-main.ts, with build-page.ts and cheerio) into builder/build.mjs, the script
// the builder repo's workflow runs; `pivot-studio builder setup` copies the builder/ folder into that repo. esbuild and
// tailwindcss stay outside the bundle (a native binary, and Tailwind's own stylesheets): builder/package.json installs
// them. The file is committed; test/builder.test.ts rebuilds it in memory and fails when the committed copy is stale.
//
// `node packages/core/scripts/build-builder.mjs` (pnpm builder:build) writes it; add --lock to refresh
// builder/package-lock.json after changing builder/package.json (it asks registry.npmjs.org).
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { build } from "esbuild";

const here = path.dirname(fileURLToPath(import.meta.url));
export const BUILDER_DIR = path.resolve(here, "../../../builder");
export const OUTPUT = path.join(BUILDER_DIR, "build.mjs");

// cheerio's browser build: the same parser and API, without the HTTP client (undici) and encodings its Node build adds
// for loading pages by URL, which the build never does (about 1.6 MB less)
const cheerioDir = path.dirname(createRequire(import.meta.url).resolve("cheerio/package.json"));

export const buildOptions = {
  absWorkingDir: path.resolve(here, ".."),
  entryPoints: ["src/builder-main.ts"],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  external: ["esbuild", "tailwindcss"],
  alias: { cheerio: path.join(cheerioDir, "dist/browser/index.js") },
  banner: {
    js: "// Generated by packages/core/scripts/build-builder.mjs from PIVOT's source: don't edit it by hand.\nimport { createRequire as __pivotCreateRequire } from 'node:module'; const require = __pivotCreateRequire(import.meta.url);",
  },
  legalComments: "eof",
  logLevel: "warning",
};

/** The bundle as text, without writing it. */
export async function bundleBuilder() {
  const out = await build({ ...buildOptions, write: false, outfile: "build.mjs" });
  return out.outputFiles[0].text;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = await bundleBuilder();
  fs.writeFileSync(OUTPUT, text);
  console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)} (${(text.length / 1024).toFixed(0)} KB)`);
  if (process.argv.includes("--lock")) {
    const npm = spawnSync(
      "npm",
      [
        "install",
        "--package-lock-only",
        "--ignore-scripts",
        "--no-audit",
        "--no-fund",
        "--registry=https://registry.npmjs.org/",
      ],
      { cwd: BUILDER_DIR, stdio: "inherit" },
    );
    if (npm.status !== 0) process.exit(npm.status ?? 1);
    console.log(`Wrote ${path.relative(process.cwd(), path.join(BUILDER_DIR, "package-lock.json"))}`);
  }
}
